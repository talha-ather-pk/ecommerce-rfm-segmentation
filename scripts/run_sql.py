"""
Run every query in sql/analysis.sql against data_clean/harbor_pine.db.

Writes sql/results.md (each question with its result table) and saves the RFM scores
(query 05) as a table `customer_rfm` in the database and as data_clean/customer_rfm.csv.
Run: python scripts/run_sql.py   (from the project root)
"""
from pathlib import Path
import re
import sqlite3
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "data_clean" / "harbor_pine.db"
SQL = (ROOT / "sql" / "analysis.sql").read_text(encoding="utf-8")

blocks = re.split(r"^-- name: ", SQL, flags=re.M)[1:]
md = ["# SQL results", "",
      "Generated by `scripts/run_sql.py` from [`analysis.sql`](analysis.sql) on `data_clean/harbor_pine.db`.", ""]
with sqlite3.connect(DB) as con:
    print("SQLite", sqlite3.sqlite_version)
    for block in blocks:
        name, body = block.split("\n", 1)
        name = name.strip()
        question = " ".join(l[3:] for l in body.splitlines() if l.startswith("-- ") and l[3:4] != "")
        query = "\n".join(l for l in body.splitlines() if not l.startswith("--")).strip().rstrip(";")
        df = pd.read_sql_query(query, con)
        if name == "05_rfm_scores":
            df.to_sql("customer_rfm", con, index=False, if_exists="replace")
            df.to_csv(ROOT / "data_clean" / "customer_rfm.csv", index=False)
            shown = df.sort_values("monetary", ascending=False).head(10)
            note = f"\n\n_{len(df):,} customers scored; top 10 by spend shown. Full table: `data_clean/customer_rfm.csv`._"
        else:
            shown, note = df, ""
        md += [f"## {name.replace('_', ' ', 1)}", "", f"_{question.split('.')[0]}._" if question else "",
               "", "```sql", query, "```", "", shown.astype(object).where(shown.notna(), None).to_markdown(index=False, floatfmt=",.2f", intfmt=",", missingval="–") + note, ""]
        print(f"{name}: {len(df):,} rows")
(ROOT / "sql" / "results.md").write_text("\n".join(md), encoding="utf-8")
print("wrote sql/results.md")
